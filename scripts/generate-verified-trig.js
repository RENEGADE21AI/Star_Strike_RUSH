"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { ANGLE_UNITS, TRIG_UNITS } = require("../shared/verified-run/constants");

const outputPath = path.resolve(__dirname, "..", "shared", "verified-run", "trig-table.js");
const values = Array.from({ length: ANGLE_UNITS }, (_, angle) => (
  Math.round(Math.sin(angle * Math.PI * 2 / ANGLE_UNITS) * TRIG_UNITS)
));
values[0] = 0;
values[ANGLE_UNITS / 4] = TRIG_UNITS;
values[ANGLE_UNITS / 2] = 0;
values[ANGLE_UNITS * 3 / 4] = -TRIG_UNITS;

const rows = [];
for (let index = 0; index < values.length; index += 16) {
  rows.push(`  ${values.slice(index, index + 16).join(", ")}`);
}

const source = `"use strict";

// Generated by scripts/generate-verified-trig.js. Do not edit by hand.
(function initializeVerifiedRunTrig(root, factory) {
  const constants = typeof module === "object" && module.exports
    ? require("./constants")
    : root.StarStrikeVerifiedRunConstants;
  const api = factory(constants);
  if (typeof module === "object" && module.exports) module.exports = api;
  Object.assign(root, api);
})(globalThis, function buildVerifiedRunTrig(constants) {
if (!constants) throw new Error("Verified run constants must load before trigonometry.");
const { ANGLE_UNITS } = constants;
const SIN_TABLE = Object.freeze([
${rows.join(",\n")}
]);
function normalizedAngle(angle) {
  const value = Number(angle);
  if (!Number.isSafeInteger(value)) throw new TypeError("Canonical angle must be a safe integer.");
  return ((value % ANGLE_UNITS) + ANGLE_UNITS) % ANGLE_UNITS;
}
function sinForAngle(angle) { return SIN_TABLE[normalizedAngle(angle)]; }
function cosForAngle(angle) { return SIN_TABLE[normalizedAngle(angle + ANGLE_UNITS / 4)]; }
return Object.freeze({ SIN_TABLE, cosForAngle, normalizedAngle, sinForAngle });
});
`;

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (existing !== source) {
    console.error("Verified trigonometry table is stale. Run npm run generate:verified-trig.");
    process.exit(1);
  }
  console.log(`Verified ${ANGLE_UNITS} canonical trigonometry values.`);
} else {
  fs.writeFileSync(outputPath, source, "utf8");
  console.log(`Generated ${ANGLE_UNITS} canonical trigonometry values.`);
}
